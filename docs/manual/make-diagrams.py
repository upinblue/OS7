def svg(w, h, body):
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {0} {1}" '
        'width="{0}" height="{1}" font-family="{2}">'
        '<rect width="{0}" height="{1}" fill="{3}"/>{4}</svg>'
    ).format(w, h, FONT, PAPER, body)


def box(x, y, w, h, fill=PAPER, stroke=LINE, rx=6, sw=1.2, dash=None):
    d = ' stroke-dasharray="{0}"'.format(dash) if dash else ""
    return ('<rect x="{0}" y="{1}" width="{2}" height="{3}" rx="{4}" fill="{5}" '
            'stroke="{6}" stroke-width="{7}"{8}/>').format(x, y, w, h, rx, fill, stroke, sw, d)


def text(x, y, s, size=13, fill=INK, weight="400", anchor="start", font=None, ls="0"):
    return ('<text x="{0}" y="{1}" font-size="{2}" fill="{3}" font-weight="{4}" '
            'text-anchor="{5}" font-family="{6}" letter-spacing="{7}">{8}</text>').format(
        x, y, size, fill, weight, anchor, font or FONT, ls, esc(s))


def esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def arrow(x1, y1, x2, y2, colour=BLUE, sw=1.6, dash=None):
    d = ' stroke-dasharray="{0}"'.format(dash) if dash else ""
    return ('<line x1="{0}" y1="{1}" x2="{2}" y2="{3}" stroke="{4}" stroke-width="{5}" '
            'marker-end="url(#a)"{6}/>').format(x1, y1, x2, y2, colour, sw, d)


