def escape(s):
    return s.replace("|", "\\|")


def render(commands, lang):
    t = TEXT[lang]
    by_module = {}
    for c in commands:
        by_module.setdefault(c["Module"], []).append(c)

    out = ["# " + t["title"], "", t["intro"], "", t["legend"], "",
           "## " + t["modules"], "",
           "| " + t["col_module"] + " | " + t["col_layer"] + " | " + t["col_count"] + " |",
           "|---|---|---|"]
    for m in MODULES:
        layer = t["product"] if m == "OS7" else t["generic"]
        out.append("| `powershell/" + m + "/` | " + layer + " | "
                   + str(len(by_module.get(m, []))) + " |")
    out.append("")

    for m in MODULES:
        cmds = by_module.get(m, [])
        if not cmds:
            continue
        out += ["## `" + m + "`", "", t["layer_note"][m], "",
                "| " + t["h_cmd"] + " | " + t["h_syn"] + " | " + t["h_par"] + " |",
                "|---|---|---|"]
        for c in cmds:
            params = []
            for p in c["Params"]:
                params.append("**" + p["Name"] + "**" if p["Mandatory"] else p["Name"])
            out.append("| `" + c["Name"] + "` | " + escape(c["Synopsis"]) + " | "
                       + (", ".join(params) if params else "*" + t["none"] + "*") + " |")
        out.append("")
    return "\n".join(out) + "\n"


def main():
    commands = ask_the_modules()
    print("    " + str(len(commands)) + " commands, asked of the modules")
    for lang in ("de", "en"):
        path = os.path.join(HERE, TEXT[lang]["file"])
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(render(commands, lang))
        print("    " + TEXT[lang]["file"])


if __name__ == "__main__":
    sys.exit(main())
