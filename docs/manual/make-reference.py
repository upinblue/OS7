#!/usr/bin/env python3
"""
Appendix A — every command, generated by asking the modules.

docs/POWERSHELL-REFERENCE.md is generated the same way and for the same reason:
a reference that is typed by hand lists what somebody believed was there. This
one asks PowerShell for `Get-Command`, `Get-Help` and the real parameter
metadata, so a cmdlet that is missing from the appendix is missing from the
product, and one that is in it exists with the parameters printed beside it.

    python docs/manual/make-reference.py

Writes docs/manual/de/90-anhang-a-referenz.md and
       docs/manual/en/90-appendix-a-reference.md

The synopses come out of the modules and are English — they are the text
`Get-Help` returns on the machine. The German appendix therefore prints the
module's own sentence and translates the surrounding structure only; inventing
a German synopsis here would put a second, unchecked description beside the one
the machine gives an operator who types `Get-Help`.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))

MODULES = ["Zfs", "Net", "Time", "Systemd", "Directory", "OS7"]

COMMON = ("Verbose Debug ErrorAction WarningAction InformationAction ProgressAction "
          "ErrorVariable WarningVariable InformationVariable OutVariable OutBuffer "
          "PipelineVariable WhatIf Confirm").split()

PS = r"""
$ErrorActionPreference = 'Stop'
foreach ($m in @({quoted})) {{
    Import-Module (Join-Path '{repo}' "powershell/$m/$m.psd1") -Force -ErrorAction SilentlyContinue
}}
$common = @({common})
$out = foreach ($c in Get-Command -Module {modules} | Sort-Object ModuleName, Name) {{
    $h = Get-Help $c.Name -ErrorAction SilentlyContinue
    [pscustomobject]@{{
        Module   = $c.ModuleName
        Name     = $c.Name
        Verb     = $c.Verb
        Synopsis = ($h.Synopsis -replace '\s+', ' ').Trim()
        Params   = @(foreach ($p in $c.Parameters.Values) {{
            if ($p.Name -notin $common) {{
                [pscustomobject]@{{
                    Name      = $p.Name
                    Type      = $p.ParameterType.Name
                    Mandatory = [bool]($p.Attributes | Where-Object {{
                        $_ -is [System.Management.Automation.ParameterAttribute] -and $_.Mandatory }})
                }}
            }}
        }})
    }}
}}
$out | ConvertTo-Json -Depth 5 -Compress
"""


def ask_the_modules():
    script = PS.format(modules=",".join(MODULES),
                       quoted=",".join("'" + m + "'" for m in MODULES),
                       repo=REPO.replace("\\", "/"),
                       common=",".join("'" + c + "'" for c in COMMON))
    p = subprocess.run(["pwsh", "-NoProfile", "-Command", script],
                       capture_output=True, text=True)
    if p.returncode != 0:
        raise SystemExit("pwsh failed:\n" + p.stderr[:2000])
    return json.loads(p.stdout.lstrip("﻿"))


