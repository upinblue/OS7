#!/usr/bin/env python3
r"""
The netplan document, checked in both languages, in seconds and without a VM.

    ./check-netplan-rule.py                          PowerShell half only
    ./check-netplan-rule.py --setup <os7-setup>      both halves
    ./check-netplan-rule.py --docker os7-build:amd64 both halves, off Linux

WHY IT EXISTS. The netplan document is generated TWICE: in C# by
`NetworkPlan.ToNetplanYaml` (installer/src/OS7.Setup/Model/NetworkPlan.cs), which
is what `os7-setup` writes during an install, and in PowerShell by
`New-NetplanDocument` (powershell/Net/Net.psm1), which is what the OS/7 cmdlets
will write on a running machine. Two implementations of one specification, in
two languages, each maintained by whoever is editing that side.

That is BUILD-NOTES #66 waiting to happen — code that replaces a spike must be
DIFFED against it, and a paraphrase written from the same notes takes a
different route. The failure mode is the worst one this subsystem has: netplan
accepts a document that matches no hardware, brings nothing up, and reports
NOTHING. No address, no route, no error, and on a headless machine that is a
site visit (L28, measured 2026-08-25).

docs/POWERSHELL-SURFACE-PLAN.md P3 is the two-step plan for having one renderer
instead of two. Until step 2 runs — it needs the Apple Silicon host, because
`run-phase3.py all` is its gate — this file is what keeps the two honest.

SO THE CASES BELOW ARE THE SPECIFICATION. They live here and nowhere else, and
each implementation is checked against THEM, byte for byte, before the two are
compared with each other. Checking the two against each other alone would pass
on the day they drift together — the same argument check-version-rule.py makes
in its own header, for the same reason.

THE C# HALF NEEDS A RUNNABLE `os7-setup`, which is a Linux binary. On macOS and
Windows there is nothing to execute, so that half is REPORTED AS NOT CHECKED
rather than skipped quietly or counted as a pass. "Cannot tell" is not "clean".

    docker run --rm --platform linux/amd64 -v "$PWD":/work os7-build:amd64 bash -c \
      'cd /work/installer/src/OS7.Setup && dotnet publish -c Release -r linux-x64 \
       -p:PublishAot=true -o /tmp/pub && cp /tmp/pub/os7-setup /work/out/'
"""
