#
# The expected document is written out IN FULL rather than as a list of
# substrings. `--self-test` on the C# side checks substrings, and substrings
# cannot see an extra line, a wrong indent or a key emitted twice — all three of
# which netplan reads as something, and none of which it complains about.
# ---------------------------------------------------------------------------

