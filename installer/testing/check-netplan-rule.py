# `None` is a real choice (L23) and it is spelled by writing NO FILE. A caller
# that renders it anyway writes an empty block, which netplan accepts and which
# configures nothing — so both sides must refuse rather than produce something.
REFUSAL = {"iface": "enp1s0", "method": "none"}

FAILS = []


def check(ok, what, detail=""):
    print(f"      {'ok  ' if ok else 'FAIL'}  {what}" + (f"   [{detail}]" if detail else ""))
    if not ok:
        FAILS.append(what)
    return ok


def show_diff(want, got):
    """The first line that differs, with both sides quoted.

    Byte-exact comparison with no diff is a check that says "no" and nothing
    else, and this file exists precisely for the case where somebody has to fix
    one of two renderers.
    """
    w = want.decode("utf-8", "replace").splitlines()
    g = got.decode("utf-8", "replace").splitlines()
    for i in range(max(len(w), len(g))):
        a = w[i] if i < len(w) else "<end of document>"
        b = g[i] if i < len(g) else "<end of document>"
        if a != b:
            print(f"            line {i + 1}")
            print(f"              want: {a!r}")
            print(f"              got:  {b!r}")
            return
    print(f"            same lines, different bytes: {len(want)} want, {len(got)} got")


# ---------------------------------------------------------------------------
# 1. The rule, in PowerShell — through powershell/Net
# ---------------------------------------------------------------------------

def pwsh():
    exe = shutil.which("pwsh")
    if not exe:
        sys.exit("pwsh not found; this check runs the real powershell/Net module.")
    return exe


# The case reaches PowerShell as JSON in a file and the document comes back as
# BYTES in a file. Neither goes through a console: pwsh's stdout is a TextWriter
# with a host-dependent encoding and newline policy, and a byte-exact check that
# reads its own answer through one is checking the console as much as the rule.
PS_DRIVER = r"""
$ErrorActionPreference = 'Stop'
Import-Module '{module}' -Force
$c = Get-Content -Raw -LiteralPath '{casefile}' | ConvertFrom-Json -AsHashtable

$a = @{{
    Renderer = if ($c.ContainsKey('renderer')) {{ $c.renderer }} else {{ 'networkd' }}
    Version  = if ($c.ContainsKey('version'))  {{ $c.version  }} else {{ 'selftest' }}
    Method   = (Get-Culture).TextInfo.ToTitleCase($c.method)
}}
if ($c.ContainsKey('iface'))    {{ $a.InterfaceName = $c.iface }}
if ($c.ContainsKey('mac'))      {{ $a.MacAddress    = $c.mac }}
if ($c.ContainsKey('address'))  {{ $a.Address       = $c.address }}
if ($c.ContainsKey('gateway'))  {{ $a.Gateway       = $c.gateway }}
if ($c.ContainsKey('dns'))      {{ $a.Nameserver    = $c.dns    -split ',' }}
if ($c.ContainsKey('search'))   {{ $a.SearchDomain  = $c.search -split ',' }}
if ($c.ContainsKey('kind') -and $c.kind -eq 'wireless') {{ $a.Wireless = $true }}
if ($c.ContainsKey('ssid'))     {{ $a.Ssid          = $c.ssid }}
if ($c.ContainsKey('hidden') -and $c.hidden -eq 'true') {{ $a.Hidden = $true }}
if ($c.ContainsKey('security')) {{
    $a.Security = (Get-Culture).TextInfo.ToTitleCase($c.security)
}}
if ($c.ContainsKey('identity'))  {{ $a.Identity          = $c.identity }}
if ($c.ContainsKey('anonymous')) {{ $a.AnonymousIdentity = $c.anonymous }}
if ($c.ContainsKey('cacert'))    {{ $a.CaCertificate     = $c.cacert }}
# P7: a secret is a [securestring] at every boundary, including a test's.
if ($c.ContainsKey('psk')) {{
    $a.Psk = ConvertTo-SecureString $c.psk -AsPlainText -Force
}}
if ($c.ContainsKey('password')) {{
    $a.Password = ConvertTo-SecureString $c.password -AsPlainText -Force
}}

try {{
    $doc = New-NetplanDocument @a
}} catch [System.InvalidOperationException] {{
    [System.IO.File]::WriteAllBytes('{outfile}', [byte[]]@())
    exit 3
}}
[System.IO.File]::WriteAllBytes('{outfile}',
    [System.Text.Encoding]::UTF8.GetBytes($doc))
"""


def powershell_render(lab, case, n):
    casefile = os.path.join(lab, f"case{n}.json")
    outfile = os.path.join(lab, f"case{n}.yaml")
    with open(casefile, "w", encoding="utf-8") as f:
        json.dump(case, f)
    script = PS_DRIVER.format(module=MODULE.replace("'", "''"),
                              casefile=casefile.replace("'", "''"),
                              outfile=outfile.replace("'", "''"))
    p = subprocess.run([pwsh(), "-NoProfile", "-NonInteractive", "-Command", script],
                       capture_output=True, text=True)
    if p.returncode == 3:
        return None, 3
    if p.returncode != 0:
        raise SystemExit(f"pwsh exited {p.returncode}:\n{p.stdout}\n{p.stderr}")
    with open(outfile, "rb") as f:
        return f.read(), 0


def powershell_rule(lab):
    print("\n  the netplan document — PowerShell, through New-NetplanDocument")
    for n, (name, case, want) in enumerate(CASES):
        got, _ = powershell_render(lab, case, n)
        if not check(got == want.encode("utf-8"), name):
            show_diff(want.encode("utf-8"), got)

    _, code = powershell_render(lab, REFUSAL, 999)
    check(code == 3, "Method None refuses to render a document")
    return True


# ---------------------------------------------------------------------------
# 2. The rule, in C# — through `os7-setup --netplan-render`
# ---------------------------------------------------------------------------

def csharp_render(argv, case):
    pairs = [f"{k}={v}" for k, v in case.items()]
    p = subprocess.run(list(argv) + ["--netplan-render"] + pairs, capture_output=True)
    return p.stdout, p.returncode, p.stderr.decode("utf-8", "replace")


def csharp_rule(argv):
    print("\n  the netplan document — C#, through os7-setup --netplan-render")
    try:
        got, code, err = csharp_render(argv, CASES[0][1])
    except OSError as e:
        print(f"      NOTE  NOT CHECKED. Could not run os7-setup: {e}")
        print("      NOTE  os7-setup is a Linux binary. --docker <image> runs it in a container.")
        return False
    if code != 0:
        # An old binary predates the flag and says "unknown option". That is a
        # missing check, not a failing one, and calling it a failure would train
        # whoever sees it to ignore this file.
        if "unknown option" in err:
            print("      NOTE  NOT CHECKED. This os7-setup predates --netplan-render.")
            print("      NOTE  Rebuild it with the container one-liner in this file's header.")
            return False
        check(False, "os7-setup --netplan-render exited 0", f"{code}: {err.strip()}")
        return True

    for name, case, want in CASES:
        got, code, err = csharp_render(argv, case)
        if code != 0:
            check(False, name, f"exited {code}: {err.strip()}")
            continue
        if not check(got == want.encode("utf-8"), name):
            show_diff(want.encode("utf-8"), got)

    _, code, _ = csharp_render(argv, REFUSAL)
    check(code == 3, "Method None refuses to render a document")
    return True


def find_setup(explicit):
    for candidate in (explicit, os.environ.get("OS7_SETUP"),
                      os.path.join(REPO, "out", "os7-setup-x64"),
                      os.path.join(REPO, "out", "os7-setup")):
        if candidate and os.path.isfile(candidate):
            return candidate
    return None


def setup_argv(setup, image):
    """How to invoke os7-setup: directly, or through a container.

    The container route is not a convenience. os7-setup is a Linux binary and
    this repository is developed from a Mac and a Windows box, so without it the
    C# half is unrunnable on the machine where the renderer is usually being
    edited — and a check that reports NOT CHECKED for ever is how one
    specification quietly becomes two.
    """
    if not image:
        return [setup]
    rel = os.path.relpath(os.path.abspath(setup), REPO).replace(os.sep, "/")
    if rel.startswith(".."):
        sys.exit(f"--docker needs an os7-setup inside the repository; {setup} is not.")
    argv = ["docker", "run", "--rm"]
    # Only when the tag says so. Passing --platform unconditionally would force
    # emulation on a host that already matches the image.
    tag = image.rsplit(":", 1)[-1]
    if tag in ("amd64", "arm64"):
        argv += ["--platform", f"linux/{tag}"]
    return argv + ["-v", f"{REPO}:/work", image, f"/work/{rel}"]


def main():
    ap = argparse.ArgumentParser(description="the netplan document, both languages")
    ap.add_argument("--setup", help="a runnable os7-setup, for the C# half")
    ap.add_argument("--docker", metavar="IMAGE",
                    help="run os7-setup in this image (e.g. os7-build:amd64), for a "
                         "host that cannot execute a Linux binary")
    args = ap.parse_args()

    print("### the netplan document (docs/POWERSHELL-SURFACE-PLAN.md P3)")
    print(f"### {len(CASES)} cases, plus the refusal")
    lab = tempfile.mkdtemp(prefix="os7-netplan-rule-")
    ran = []
    try:
        powershell_rule(lab)
        ran.append("PowerShell")

        setup = find_setup(args.setup)
        if setup:
            if csharp_rule(setup_argv(setup, args.docker)):
                ran.append("C#")
        else:
            print("\n  the netplan document — C#")
            print("      NOTE  NOT CHECKED. No os7-setup was found.")
            print("      NOTE  Pass --setup <path>, or set OS7_SETUP, or drop one in out/.")
        if "C#" not in ran:
            print("      NOTE  Build one with the container one-liner in this file's header,")
            print("      NOTE  then either run this on Linux or add --docker os7-build:<arch>.")
    finally:
        if os.environ.get("NETPLAN_RULE_KEEP"):
            print(f"\n(kept: {lab})")
        else:
            shutil.rmtree(lab, ignore_errors=True)

    print()
    if FAILS:
        print(f"{len(FAILS)} check(s) FAILED")
        return 1
    print(f"all checks passed — {', '.join(ran)} produce the same bytes for the same cases.")
    # Name what actually ran. "Both agree" and "the one that could run is right"
    # are different claims, and only one of them is earned in a given run.
    missing = [n for n in ("PowerShell", "C#") if n not in ran]
    if missing:
        print(f"NOT COMPARED IN THIS RUN: {', '.join(missing)}. The document has two "
              f"implementations and this run exercised {len(ran)}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
